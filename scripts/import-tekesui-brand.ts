/** Offline import of TekesUI's already compiled Sage palette. No second color algorithm. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const root = process.argv[2];
if (!root)
  throw new Error(
    'Usage: npx tsx scripts/import-tekesui-brand.ts /path/to/TekesUI',
  );
interface Token {
  name: string;
  value: string | Record<string, string>;
}
interface Preset {
  id: string;
  seed_srgb: string;
  color: { themes: string[]; tokens: Token[] };
}
const bytes = await readFile(resolve(root, 'design/gallery/brands.json'));
const document = JSON.parse(bytes.toString()) as {
  inputs_sha256: Record<string, string>;
  presets: Preset[];
};
for (const [path, expected] of Object.entries(document.inputs_sha256)) {
  const actual = createHash('sha256')
    .update(await readFile(resolve(root, path)))
    .digest('hex');
  if (actual !== expected)
    throw new Error(`Stale TekesUI palette input: ${path}`);
}
const sage = document.presets.find((p) => p.id === 'sage');
if (!sage) throw new Error('TekesUI Sage preset is missing');
const tokens = new Map(sage.color.tokens.map((t) => [t.name, t.value]));
function color(
  name: string,
  theme: string,
  visited = new Set<string>(),
): string {
  if (visited.has(name)) throw new Error(`Circular color token: ${name}`);
  visited.add(name);
  const value = tokens.get(name);
  if (!value) throw new Error(`Unknown color token: ${name}`);
  if (typeof value === 'string' && value.startsWith('{'))
    return color(value.slice(1, -1), theme, visited);
  return typeof value === 'string' ? value : value[theme];
}
const roles: Record<string, string> = {
  accent: 'accent',
  action: 'action-primary-ground',
  'action-hover': 'action-primary-hover',
  'action-pressed': 'action-primary-pressed',
  'accent-foreground': 'action-primary-foreground',
  'accent-subtle': 'accent-subtle-ground',
};
const themes = Object.fromEntries(
  sage.color.themes.map((theme) => [
    theme,
    Object.fromEntries(
      Object.entries(roles).map(([css, role]) => [css, color(role, theme)]),
    ),
  ]),
);
const metadata = {
  format: 'tekeswebui-brand/1',
  source: 'https://github.com/TekesApps/TekesUI',
  sourceFile: 'design/gallery/brands.json',
  sourceSHA256: createHash('sha256').update(bytes).digest('hex'),
  preset: sage.id,
  seed: sage.seed_srgb,
  inputsSHA256: document.inputs_sha256,
  themes,
};
const block = (selector: string, theme: string) =>
  `${selector} {\n  --brand-seed: ${sage.seed_srgb};\n${Object.entries(
    themes[theme],
  )
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')}\n}\n`;
const css =
  '/* Generated by scripts/import-tekesui-brand.ts from TekesUI Sage. Do not hand edit. */\n' +
  block(':root', 'light') +
  block(':root[data-theme="dark"]', 'dark') +
  '@media (prefers-contrast: more) {\n' +
  block(':root', 'light-ic') +
  block(':root[data-theme="dark"]', 'dark-ic') +
  '}\n';
await writeFile(new URL('../src/theme/brand.css', import.meta.url), css);
await writeFile(
  new URL('../design/brand.json', import.meta.url),
  JSON.stringify(metadata, null, 2) + '\n',
);
console.log(
  `Imported TekesUI ${sage.id} (${sage.seed_srgb}), four themes, verified compiler input hashes.`,
);
